function handoffNote({ role, task, provider, model, usage, recentDecisions, reason }) {
  const ts = new Date().toISOString();
  const { total, limit, pct } = usage;
  const totalFmt = total.toLocaleString();
  const limitFmt = limit.toLocaleString();
  const isCompletion = reason === "completion";

  const decisionLines = (recentDecisions || [])
    .slice(-5)
    .map((d) => `- [${d.ts}] ${d.role}: ${d.task} (${d.output_lines} output lines)`)
    .join("\n") || "  (no prior decisions in this session)";

  return [
    `# Agent Handoff — ${ts}`,
    "",
    isCompletion
      ? `> This handoff was generated automatically when the task completed successfully.`
      : `> This handoff was generated automatically because the context window reached **${pct}% capacity**.`,
    `> Start a fresh session and include this note so the agent can pick up where you left off.`,
    "",
    "## Session context",
    "",
    `| Field | Value |`,
    `|---|---|`,
    `| Role | \`${role}\` |`,
    `| Task | ${task} |`,
    `| Provider | ${provider} |`,
    `| Model | ${model} |`,
    `| Tokens used | ${totalFmt} / ${limitFmt} (${pct}%) |`,
    "",
    "## What was accomplished (last 5 decisions)",
    "",
    decisionLines,
    "",
    "## Prompt for your new session",
    "",
    "Paste this at the start of your next `agent-contract run` or conversation:",
    "",
    "```",
    `I am continuing a previous agent-contract session. Context window was at ${pct}%.`,
    `Role: ${role}`,
    `Task: ${task}`,
    ``,
    `Previous decisions are logged in .agent/memory/decisions.jsonl.`,
    `Pick up from where we left off and do not repeat completed work.`,
    "```",
    "",
    `---`,
    `_Generated by agent-contract token manager at ${ts}_`,
    "",
  ].join("\n");
}

function writeHandoffScript() {
  return `#!/usr/bin/env bash
# write-handoff.sh — auto-writes a session handoff note at turn end.
# Wired to the Claude Code Stop hook via .claude/settings.json.
# Non-blocking: the Stop hook ignores the exit code.
set -uo pipefail

ROOT="$(cd "$(dirname "\${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_ROOT="$(cd "$ROOT/.." && pwd)"
MEMORY_DIR="$ROOT/memory"
SESSION_DIR="$ROOT/session"

mkdir -p "$MEMORY_DIR" "$SESSION_DIR"

ROLE="unknown"
if [[ -f "$SESSION_DIR/active-role.txt" ]]; then
  ROLE=\$(tr -d '[:space:]' < "$SESSION_DIR/active-role.txt")
fi

# Fallback 1: extract role from the most recent decisions.jsonl entry that
# carries a "role" field (the documented decision schema includes one).
if [[ "$ROLE" == "unknown" || -z "$ROLE" ]] && [[ -f "$MEMORY_DIR/decisions.jsonl" ]]; then
  _r=\$(grep -oE '"role"[[:space:]]*:[[:space:]]*"[a-zA-Z]+"' "$MEMORY_DIR/decisions.jsonl" | tail -1 | grep -oE '"[a-zA-Z]+"$' | tr -d '"' || true)
  [[ -n "\$_r" ]] && ROLE="\$_r"
fi

# Fallback 2: inherit the role from the most recent prior handoff that named a
# real one — a stale-but-plausible role beats a silent "unknown".
if [[ "$ROLE" == "unknown" || -z "$ROLE" ]]; then
  _prev=\$(ls -t "$MEMORY_DIR"/handoff-*.md 2>/dev/null | head -1 || true)
  if [[ -n "\$_prev" ]]; then
    _r=\$(grep -A1 '^## Role' "\$_prev" 2>/dev/null | tail -1 | tr -d '[:space:]' || true)
    [[ -n "\$_r" && "\$_r" != "unknown"* ]] && ROLE="\$_r"
  fi
fi

# Still unknown → leave a diagnosable marker, not a bare "unknown". This means
# active-role.txt was absent at Stop: pre-generate.sh was not run in
# this repo — commonly because the session ran from a different working directory.
ROLE_DIAG=""
if [[ "$ROLE" == "unknown" || -z "$ROLE" ]]; then
  ROLE="unknown"
  ROLE_DIAG=" (active-role.txt absent at Stop — pre-generate not run in this repo)"
fi

DECISIONS="(no decisions logged this session)"
if [[ -f "$MEMORY_DIR/decisions.jsonl" ]]; then
  d=$(tail -5 "$MEMORY_DIR/decisions.jsonl" 2>/dev/null || true)
  [[ -n "$d" ]] && DECISIONS="$d"
fi

CHANGED=""
if [[ -d "$PROJECT_ROOT/.git" ]]; then
  c=$(git -C "$PROJECT_ROOT" diff --name-only HEAD 2>/dev/null || true)
  if [[ -z "$c" ]]; then
    c=$(git -C "$PROJECT_ROOT" diff --name-only --cached 2>/dev/null || true)
  fi
  [[ -n "$c" ]] && CHANGED="$c"
fi

# Skip write when nothing changed — avoids noise on trivial turns
[[ -z "$CHANGED" ]] && exit 0
CHANGED_DISPLAY="$CHANGED"

TS=$(date +%Y-%m-%d-%H%M%S 2>/dev/null || echo "ts")
OUTFILE="$MEMORY_DIR/handoff-done-\${TS}.md"

{
  printf '# Agent Handoff — %s\\n\\n' "$TS"
  printf '> Auto-generated by agent-contract Stop hook.\\n'
  printf '> Prior role: %s (scope: .agent/roles/%s.yaml). Read what the next task needs.\\n\\n' "$ROLE" "$ROLE"
  printf '## Role\\n%s%s\\n\\n' "$ROLE" "$ROLE_DIAG"
  printf '## Files Changed\\n%s\\n\\n' "$CHANGED_DISPLAY"
  printf '## Last 5 Decisions\\n%s\\n\\n' "$DECISIONS"
  printf '## Resume Prompt\\n\\n\`\`\`\\nContinuing from handoff %s. Role: %s.\\nContext if needed: .agent/memory/codebase-map.md, .agent/memory/decisions.jsonl.\\n\`\`\`\\n' "$TS" "$ROLE"
} > "$OUTFILE"

printf 'write-handoff: saved → .agent/memory/handoff-done-%s.md\\n' "$TS" >&2

# Compact old handoffs in the background — keep the 5 most recent, archive the rest.
# Runs detached so it never adds latency to the session.
(
  KEEP=5
  all=$(ls -t "$MEMORY_DIR"/handoff-*.md 2>/dev/null || true)
  count=$(printf '%s\\n' "$all" | grep -c '[^[:space:]]' 2>/dev/null || echo 0)
  if (( count > KEEP )); then
    ARCHIVE="$MEMORY_DIR/handoff-archive.jsonl"
    to_archive=$(printf '%s\\n' "$all" | tail -n "+$((KEEP + 1))")
    while IFS= read -r f; do
      [[ -z "$f" ]] && continue
      fname=$(basename "$f")
      ts=$(printf '%s' "$fname" | grep -oE '[0-9]{4}-[0-9]{2}-[0-9]{2}-[0-9]+' | head -1 || echo "unknown")
      role=$(grep -A1 '^## Role' "$f" 2>/dev/null | tail -1 | tr -d '[:space:]' || echo "unknown")
      files=$(awk '/^## Files Changed/{f=1;next} f&&/^##/{exit} f{printf "%s,", $0}' "$f" 2>/dev/null | sed 's/,$//')
      printf '{"ts":"%s","role":"%s","files":"%s","source":"%s"}\\n' "$ts" "$role" "$files" "$fname" >> "$ARCHIVE"
      rm -f "$f"
    done <<< "$to_archive"
  fi
) >/dev/null 2>&1 &

exit 0
`;
}

// scope-lib.sh — shared scope engine sourced by all three scope guards
// (scope-check.sh = action layer on file tools, bash-write-guard.sh = action
// layer on Bash, post-generate.sh = outcome layer on the git diff). Keeping the
// parsing + protected-path logic in one place stops the three copies drifting.
// macOS ships bash 3.2, so this avoids mapfile and other bash 4+ features.
function scopeLibScript() {
  return `#!/usr/bin/env bash
# scope-lib.sh — shared scope logic. SOURCED by scope-check.sh, bash-write-guard.sh
# and post-generate.sh; not meant to run standalone (defines functions only, no exits,
# no 'set' so it can't alter the caller's shell options).
#
# This file is itself contract-controlled: the guards below refuse agent writes to it.

# scope_is_protected REL_PATH
#   Return 0 (true) when REL_PATH is a contract-controlled file the agent must never
#   write — doing so would let it rewrite its own role, widen its scope, or disable a
#   guard. These are changed out-of-band (human / \`agent-contract update\`), never from
#   inside an agent session. Paths are project-root-relative.
scope_is_protected() {
  case "$1" in
    .agent/session/active-role.txt) return 0 ;;
    .agent/roles/*)                 return 0 ;;
    .agent/checks/*)                return 0 ;;
    .claude/settings.json)          return 0 ;;
    .claude/settings.local.json)    return 0 ;;
    .github/workflows/*)            return 0 ;;
  esac
  return 1
}

# scope_is_protected_abs ABS_PATH
#   Return 0 (true) for paths OUTSIDE this repo that must still never be written.
#   A repo-level contract deliberately does not govern the whole filesystem, but two
#   things live outside the repo and decide whether the contract is enforced at all:
#     1. the installed agent-contract package. Every check script is regenerated from
#        its templates, so editing them and re-running a plain update neuters the
#        guards without ever touching a protected path inside the repo.
#     2. hook settings anywhere. The PreToolUse wiring is what makes any of this run.
#     3. CI workflow definitions. A workflow runs with the repository's secrets, so an
#        agent that can add one can publish a tampered package or exfiltrate a token.
#        Same reasoning as package.json: not a task action, a human review step.
#   Everything else outside the repo — tmp files, scratch dirs, sibling projects —
#   stays allowed. This is a toolchain-integrity rule, not a sandbox.
scope_is_protected_abs() {
  case "$1" in
    */agent-contract/lib/*|*/agent-contract/bin/*)         return 0 ;;
    */agent-contract/package.json)                         return 0 ;;
    */.claude/settings.json|*/.claude/settings.local.json)  return 0 ;;
    */.github/workflows/*)                                  return 0 ;;
  esac
  return 1
}

# scope_role_patterns_for ROLE_FILE KEY
#   Like scope_role_patterns but for ONE key (may_create or may_modify). Role inference
#   needs them apart: creating a file is governed by may_create, editing an existing one
#   by may_modify, and conflating the two makes almost every path look ambiguous.
scope_role_patterns_for() {
  local role_file="$1" want="$2" line in_block=0 p
  [[ -f "$role_file" ]] || return 0
  while IFS= read -r line; do
    if [[ "$line" =~ ^[[:space:]]*(may_create|may_modify|may_delete)[[:space:]]*: ]]; then
      in_block=0
      if [[ "$line" =~ ^[[:space:]]*"$want"[[:space:]]*: ]]; then
        [[ "$line" =~ \[\] ]] || in_block=1
      fi
      continue
    fi
    if [[ $in_block -eq 1 ]]; then
      if [[ "$line" =~ ^[[:space:]]*-[[:space:]]+(.+) ]]; then
        p="\${BASH_REMATCH[1]//\\"/}"
        printf '%s\\n' "$p"
      else
        in_block=0
      fi
    fi
  done < "$role_file"
}

# scope_role_patterns ROLE_FILE
#   Print the role's allowed globs (may_create + may_modify), one per line.
#   An explicit empty list ([]) yields no lines — callers treat "no patterns" as
#   fail-closed (a read-only role), NOT as "anything goes".
scope_role_patterns() {
  local role_file="$1" line in_block=0 p
  [[ -f "$role_file" ]] || return 0
  while IFS= read -r line; do
    if [[ "$line" =~ ^[[:space:]]*(may_create|may_modify)[[:space:]]*: ]]; then
      [[ "$line" =~ \\[\\] ]] && { in_block=0; continue; }
      in_block=1; continue
    fi
    if [[ $in_block -eq 1 ]]; then
      if [[ "$line" =~ ^[[:space:]]*-[[:space:]]+(.+) ]]; then
        p="\${BASH_REMATCH[1]//\\\"/}"
        printf '%s\\n' "$p"
      else
        in_block=0
      fi
    fi
  done < "$role_file"
}
`;
}

function scopeCheckScript() {
  return `#!/usr/bin/env bash
# scope-check.sh — PreToolUse hook for Claude Code (Write|Edit|MultiEdit).
# NOTE ON EXIT CODES: PreToolUse blocks ONLY on exit 2. Any other non-zero code is
# treated as a non-blocking hook error and THE TOOL CALL PROCEEDS -- a guard exiting 1
# prints its refusal and lets the write through anyway. Keep these at 2.
# ACTION layer: reads the tool-call JSON from stdin and blocks the write when the
# target is contract-controlled or outside the active role's declared scope.
# Exits non-zero to BLOCK the tool call. Registered in .claude/settings.json by
# \`agent-contract init\`. Pairs with bash-write-guard.sh (Bash writes) and
# post-generate.sh (the authoritative diff/outcome check).
set -uo pipefail

ROOT="$(cd "$(dirname "\${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_ROOT="$(cd "$ROOT/.." && pwd)"
SESSION_DIR="$ROOT/session"
source "$ROOT/checks/scope-lib.sh"

# Read tool input JSON from stdin (Claude Code sends this for PreToolUse hooks)
TOOL_INPUT=$(cat 2>/dev/null || true)
[[ -z "$TOOL_INPUT" ]] && exit 0

# Extract file_path from tool input JSON (handles Write, Edit, MultiEdit)
FILE_PATH=$(printf '%s' "$TOOL_INPUT" | grep -oE '"file_path"[[:space:]]*:[[:space:]]*"[^"]*"' | head -1 | grep -oE '"[^"]*"$' | tr -d '"' 2>/dev/null || true)
[[ -z "$FILE_PATH" ]] && exit 0

# Make path relative to project root
REL_PATH="\${FILE_PATH#$PROJECT_ROOT/}"
# Outside this repo. Not ours to police in general — except the toolchain that decides
# whether the contract is enforced at all, which is reachable from any target repo.
if ! declare -f scope_is_protected_abs >/dev/null 2>&1; then
  # Stale scope-lib.sh. Define the same rule locally rather than fall open: an
  # undefined function returns 127, which reads as "not protected".
  scope_is_protected_abs() {
    case "$1" in
      */agent-contract/lib/*|*/agent-contract/bin/*)         return 0 ;;
      */agent-contract/package.json)                         return 0 ;;
      */.claude/settings.json|*/.claude/settings.local.json)  return 0 ;;
    esac
    return 1
  }
fi

if [[ "$REL_PATH" = /* ]]; then
  if scope_is_protected_abs "$REL_PATH"; then
    printf 'scope-check: BLOCKED reason=toolchain-write path=%s fix=out-of-band\\n' "$REL_PATH" >&2
    exit 2
  fi
  exit 0
fi

# Gap 0 — contract-controlled files are NEVER agent-writable, even though they live
# under .agent/. Without this the agent could rewrite active-role.txt to switch roles
# mid-task, widen a role YAML, or edit the guards themselves.
if scope_is_protected "$REL_PATH"; then
  printf 'scope-check: BLOCKED reason=contract-controlled path=%s fix=out-of-band\\n' "$REL_PATH" >&2
  exit 2
fi

# Other contract infrastructure (memory, decisions, handoffs, session notes) stays writable.
case "$REL_PATH" in .agent/*) exit 0 ;; esac

# No active role yet. Rather than block the first source write of every session —
# a guaranteed wasted turn for anyone not dispatching through agent-contract run —
# derive the role from the target when exactly one role can account for it.
#
# This grants nothing extra: every write is still checked against that role's globs, so
# inference can only pick a role that would have permitted this write anyway. What it
# must not do is skip the spec gate, so a role declaring inputs_required is never
# inferred; generating new source still requires pre-generate.sh with a filled-in spec.
#
# may_create vs may_modify is decided by whether the file already exists, which is what
# makes the answer unique in practice: editing lib/x.js is integrator, creating it is
# generator (and so needs a spec).
if [[ ! -f "$SESSION_DIR/active-role.txt" ]]; then
  if [[ -e "$PROJECT_ROOT/$REL_PATH" ]]; then WANT_KEY="may_modify"; else WANT_KEY="may_create"; fi

  inferred=()
  needs_spec=()
  for rf in "$ROOT"/roles/*.yaml; do
    [[ -f "$rf" ]] || continue
    cand="$(basename "$rf" .yaml)"
    matched=0
    while IFS= read -r pat; do
      [[ -z "$pat" ]] && continue
      case "$REL_PATH" in $pat) matched=1; break ;; esac
    done < <(scope_role_patterns_for "$rf" "$WANT_KEY")
    if [[ $matched -eq 1 ]]; then
      if grep -q '^inputs_required:' "$rf"; then needs_spec+=("$cand"); else inferred+=("$cand"); fi
    fi
  done

  if (( \${#inferred[@]} == 1 )); then
    mkdir -p "$SESSION_DIR"
    printf '%s\\n' "\${inferred[0]}" > "$SESSION_DIR/active-role.txt"
    printf 'scope-check: role inferred=%s path=%s basis=%s\\n' "\${inferred[0]}" "$REL_PATH" "$WANT_KEY" >&2
    exit 0
  fi

  if (( \${#inferred[@]} == 0 && \${#needs_spec[@]} > 0 )); then
    printf 'scope-check: BLOCKED reason=spec-required roles=%s fix="pre-generate.sh <spec> <role>"\\n' "$(IFS=,; echo "\${needs_spec[*]}")" >&2
    exit 2
  fi

  if (( \${#inferred[@]} > 1 )); then
    printf 'scope-check: BLOCKED reason=ambiguous-role candidates=%s fix="pre-generate.sh <spec> <role>"\\n' "$(IFS=,; echo "\${inferred[*]}")" >&2
    exit 2
  fi

  printf 'scope-check: BLOCKED reason=no-role-covers-path path=%s fix="pre-generate.sh <spec> <role>" roles=${ROLES.join(",")}\\n' "$REL_PATH" >&2
  exit 2
fi

ROLE=$(tr -d '[:space:]' < "$SESSION_DIR/active-role.txt")
ROLE_FILE="$ROOT/roles/\${ROLE}.yaml"

# Fail-closed: declared role has no definition file → block (was: silently allow).
if [[ ! -f "$ROLE_FILE" ]]; then
  printf 'scope-check: BLOCKED reason=unknown-role role=%s roles=${ROLES.join(",")}\\n' "$ROLE" >&2
  exit 2
fi

# Parse may_create + may_modify globs via the shared engine (bash 3.2-safe; no mapfile).
# Deduplicate: scope_role_patterns unions may_create and may_modify, and a role that
# lists the same globs under both (documenter does) would otherwise print every path
# twice in the denial message.
allowed=()
while IFS= read -r p; do
  [[ -n "$p" ]] || continue
  seen=0
  for a in "\${allowed[@]:-}"; do [[ "$a" == "$p" ]] && { seen=1; break; }; done
  (( seen )) || allowed+=("$p")
done < <(scope_role_patterns "$ROLE_FILE")

# Gap 3 — empty scope is FAIL-CLOSED. A role that declares no writable globs is
# read-only (e.g. reviewer, security) and may not write source. Previously an empty
# scope passed everything, which inverted the intent.
if (( \${#allowed[@]} == 0 )); then
  printf 'scope-check: BLOCKED reason=read-only-role role=%s path=%s\\n' "$ROLE" "$REL_PATH" >&2
  exit 2
fi

# Check file against allowed patterns
for pattern in "\${allowed[@]}"; do
  case "$REL_PATH" in $pattern) exit 0 ;; esac
done

printf 'scope-check: BLOCKED reason=out-of-scope role=%s path=%s allowed=%s\\n' "$ROLE" "$REL_PATH" "\${allowed[*]}" >&2
exit 2
`;
}

// bash-write-guard.sh — ACTION layer on the Bash tool. scope-check only sees the
// file tools (Write/Edit/MultiEdit); a Bash command like \`echo x > .agent/roles/y\`
// would otherwise slip past. This guard is deliberately narrow and high-precision:
// it blocks Bash commands that write to CONTRACT-CONTROLLED paths (the self-escape
// vector). General source writes via Bash are not parseable reliably, so those are
// left to the authoritative outcome check in post-generate.sh.
function bashWriteGuardScript() {
  return `#!/usr/bin/env bash
# bash-write-guard.sh — PreToolUse hook for Claude Code (Bash).
# NOTE ON EXIT CODES: PreToolUse blocks ONLY on exit 2. Any other non-zero code is
# treated as a non-blocking hook error and THE TOOL CALL PROCEEDS -- a guard exiting 1
# prints its refusal and lets the write through anyway. Keep these at 2.
# Best-effort ACTION layer: blocks Bash commands that appear to write to or delete a
# contract-controlled file (active-role.txt, roles/*, checks/*, .claude/settings*).
# This is the one gap scope-check.sh can't see. It is intentionally conservative —
# when in doubt it ALLOWS, because post-generate.sh's diff check is the authoritative
# backstop for any file change regardless of how it was made.
set -uo pipefail

# Pull the command string out of the Bash tool-call JSON. Loose extraction is fine:
# we only need to know whether a write construct sits ADJACENT to a contract path.
TOOL_INPUT=$(cat 2>/dev/null || true)
[[ -z "$TOOL_INPUT" ]] && exit 0
CMD=$(printf '%s' "$TOOL_INPUT" | sed -E 's/.*"command"[[:space:]]*:[[:space:]]*"//; s/"[[:space:]]*}*[[:space:]]*$//')
[[ -z "$CMD" ]] && exit 0

# Contract-controlled paths (must mirror scope_is_protected in scope-lib.sh).
# Mirrors scope_is_protected AND scope_is_protected_abs in scope-lib.sh. The
# agent-contract entry matters because the installed package sits outside the repo and
# every check script is regenerated from its templates.
PROT='(\\.agent/session/active-role\\.txt|\\.agent/roles/|\\.agent/checks/|\\.claude/settings(\\.local)?\\.json|agent-contract/(lib|bin)/|\\.github/workflows/)'

# Block only when a write construct targets a protected path. The protected path must be
# ADJACENT to the write op, so harmless reads with unrelated redirects (e.g.
# 'cat .agent/roles/x 2>/dev/null') don't trip the guard:
#   RE1 — redirection straight into a protected path:  > .agent/roles/x   >>'.agent/checks/y'
#   RE2 — a mutating command (tee/sed -i/rm/cp/mv/dd/truncate/install/ln) with a protected
#         arg before the next ; | & separator. Command words are token-anchored so we don't
#         match substrings like "add" (dd), "vuln" (ln) or "remove" (rm).
RE1=">>?[[:space:]]*[\\"']?$PROT"
RE2="(^|[;&|[:space:]])(tee|sed[[:space:]]+-i|rm|cp|mv|dd|truncate|install|ln)([[:space:]]+[^;|&]*)?[\\"']?$PROT"

if printf '%s' "$CMD" | grep -qE "$RE1" || printf '%s' "$CMD" | grep -qE "$RE2"; then
  printf 'bash-write-guard: BLOCKED reason=contract-controlled-write fix=out-of-band paths=.agent/roles/**,.agent/checks/**,.agent/session/active-role.txt,.claude/settings*\\n' >&2
  exit 2
fi

# RE3 — the contract-rewriting escape hatch. \`update\` refuses to widen a role's scope
# unless --allow-scope-change is passed, and --force overwrites roles and checks
# wholesale. Both are how a human consents to a contract change; neither is something a
# session should be able to do for itself, or the refusal is decoration. Editing the
# generator in lib/ and then re-running update is the exact path this closes.
RE3="agent-contract(\\.js)?[[:space:]]+(init|update)([[:space:]]+[^;|&]*)?[[:space:]]--(allow-scope-change|force)"

# RE4 — the non-interactive consent escape hatch. The update command gates the consent
# flags on a controlling terminal, and this variable is the documented CI bypass. A
# session has no reason to set it, and setting it is the one way to defeat the TTY check.
if printf '%s' "$CMD" | grep -q 'AGENT_CONTRACT_NONINTERACTIVE_CONSENT'; then
  printf 'bash-write-guard: BLOCKED reason=consent-bypass var=AGENT_CONTRACT_NONINTERACTIVE_CONSENT fix=human-terminal\\n' >&2
  exit 2
fi

if printf '%s' "$CMD" | grep -qE "$RE3"; then
  printf 'bash-write-guard: BLOCKED reason=contract-scope-change flag=--allow-scope-change/--force fix=human-terminal\\n' >&2
  exit 2
fi

exit 0
`;
}

