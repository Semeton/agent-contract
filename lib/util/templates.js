function conventionsDraftYaml(inferences) {
  const { sample_size, style, errors, naming, tests } = inferences;
  const lines = [];

  lines.push("# conventions.draft.yaml — DRAFT generated by `agent-contract learn`.");
  lines.push(`# Sampled ${sample_size} source file(s). Review each field then merge into conventions.yaml.`);
  lines.push("# Delete this file after merging.");
  lines.push("#");
  lines.push('schema: "agent-contract/v1"');
  lines.push("");

  // Paradigm
  if (style) {
    lines.push(`# paradigm — inferred (confidence: ${style.confidence})`);
    lines.push(`# evidence: ${style.evidence.class_files} class file(s), ${style.evidence.func_files} function-only file(s)`);
    lines.push(`paradigm: ${style.paradigm}`);
  } else {
    lines.push("# paradigm — could not infer; set manually: oop | functional | mixed");
    lines.push("paradigm: oop");
  }
  lines.push("");

  lines.push("module_size:");
  lines.push("  max_lines_per_file: 300    # default — not inferred");
  lines.push("  max_lines_per_function: 40");
  lines.push("  max_params: 4");
  lines.push("");

  lines.push("db:");
  lines.push("  transactions: required_for_multi_write");
  lines.push("  migrations: required_for_schema_change");
  lines.push("  raw_queries: forbidden_outside_repository_layer");
  lines.push("");

  // Errors
  if (errors && errors.style !== "unstructured") {
    lines.push(`# errors.style — inferred (confidence: ${errors.confidence})`);
    lines.push(`# evidence: ${errors.evidence.try_catch_files} file(s) with try/catch, ${errors.evidence.custom_error_classes} custom error class(es)`);
    lines.push("errors:");
    lines.push(`  style: ${errors.style}`);
    lines.push("  bubbling: explicit");
  } else {
    lines.push("errors:");
    lines.push("  style: typed_exceptions    # default — could not infer");
    lines.push("  bubbling: explicit");
  }
  lines.push("");

  lines.push("dependencies:");
  lines.push("  injection: constructor");
  lines.push("  new_packages: requires_human_approval");
  lines.push("");

  // Testing
  if (tests) {
    lines.push(`# testing.style — inferred (confidence: ${tests.confidence})`);
    if (tests.evidence) lines.push(`# evidence: ${tests.evidence.spec_files} spec file(s) found`);
    lines.push("testing:");
    lines.push("  required_for:");
    lines.push("  - service_layer");
    lines.push("  - controller_layer");
    lines.push(`  style: ${tests.pattern}`);
  } else {
    lines.push("testing:");
    lines.push("  required_for:");
    lines.push("  - service_layer");
    lines.push("  - controller_layer");
    lines.push("  style: arrange_act_assert    # default — no test files found");
  }
  lines.push("");

  // Naming — shown as a commented suggestion since conventions.yaml has no naming key by default
  if (naming) {
    lines.push(`# naming — inferred (confidence: ${naming.confidence})`);
    const ev = Object.entries(naming.evidence).map(([k, v]) => `${k}: ${v}`).join(", ");
    lines.push(`# evidence: ${ev}`);
    lines.push("# Uncomment to enforce:");
    lines.push("# naming:");
    lines.push(`#   files: ${naming.convention}`);
    lines.push("");
  }

  lines.push("clarification:");
  lines.push("  ask_when:");
  lines.push("  - spec_missing_input_shape");
  lines.push("  - spec_missing_error_behavior");
  lines.push("  - touching_more_than_n_files");
  lines.push("  - new_external_dependency");
  lines.push("  - schema_change");
  lines.push("  n_files_threshold: 5");

  return lines.join("\n") + "\n";
}

